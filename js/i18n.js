export const STRINGS = { en, da };

export function resolveLang(setting, navLang = '') {
  if (setting === 'da' || setting === 'en') return setting;
  return /^(da|nb|nn|no)\b/i.test(navLang) ? 'da' : 'en';
}

export function translator(lang) {
  const dict = STRINGS[lang] || en;
  return (key, params = {}) => {
    const v = dict[key] ?? en[key];
    if (v == null) return key;
    return typeof v === 'function' ? v(params) : v;
  };
}

// "chest and triceps" / "bryst, triceps og skuldre"
export function joinList(items, lang) {
  const and = (STRINGS[lang] || en).and;
  if (items.length <= 1) return items.join('');
  return items.slice(0, -1).join(', ') + ` ${and} ` + items[items.length - 1];
}
